"""
RAG Data Models for ContractRisk AI

Defines Pydantic v2 data models for evidence items, citations,
and grounded RAG responses.
"""

from typing import List, Optional
from pydantic import BaseModel, Field, ConfigDict


class RAGEvidenceItem(BaseModel):
    """
    Represents an individual retrieved clause item supplied as evidence to the LLM.
    """
    model_config = ConfigDict(frozen=True)

    clause_id: str = Field(description="Unique clause identifier.")
    document_id: str = Field(description="Parent contract document ID.")
    clause_number: Optional[str] = Field(default=None, description="Legal section/clause number.")
    clause_heading: Optional[str] = Field(default=None, description="Clause title or heading.")
    clause_text: str = Field(description="Exact text of the retrieved clause.")
    source_pages: List[int] = Field(default_factory=list, description="Source 1-indexed page numbers.")
    similarity_score: float = Field(description="Cosine similarity score from FAISS retrieval.")


class Citation(BaseModel):
    """
    Represents a specific evidence citation mapping an answer claim to a clause.
    """
    clause_id: str = Field(description="Unique clause identifier of supporting evidence.")
    clause_number: Optional[str] = Field(default=None, description="Legal section/clause number.")
    source_pages: List[int] = Field(default_factory=list, description="Source page numbers.")


class RAGResponse(BaseModel):
    """
    Structure representing a grounded RAG query answer with citations and evidence metadata.
    """
    query: str = Field(description="User input query.")
    answer: str = Field(description="Evidence-grounded answer generated by LLM or fallback response.")
    evidence: List[RAGEvidenceItem] = Field(default_factory=list, description="Retrieved contract evidence items.")
    citations: List[Citation] = Field(default_factory=list, description="Verified citations linking claims to evidence.")
    insufficient_evidence: bool = Field(default=False, description="True if evidence is missing, below threshold, or insufficient.")
    model_name: str = Field(description="Name of the local LLM used for generation.")
    retrieval_top_k: int = Field(default=5, description="Top-K parameter used during retrieval.")
    retrieval_threshold: float = Field(default=0.65, description="Similarity threshold applied.")
